//! RoCEv2 — RDMA over Converged Ethernet v2, in RHDL.
//!
//! A RoCEv2 packet is an ordinary UDP datagram to port 4791 whose
//! payload is an InfiniBand transport packet:
//!
//! ```text
//! +----------+-----------+--------+---------+-----------+---------+------+-----+
//! | Eth MAC  | IPv4 / v6 |  UDP   | IB BTH  | ext. hdrs | payload | ICRC | FCS |
//! |  14 B    | 20 / 40 B |  8 B   |  12 B   | 0/4/16 B  |  0..PMTU|  4 B | 4 B |
//! +----------+-----------+--------+---------+-----------+---------+------+-----+
//!                        dport=4791
//! ```
//!
//! Everything left of the BTH is ordinary networking. Everything from
//! the BTH rightward is InfiniBand, and that is what this crate covers:
//! the transport headers as typed [`rhdl::prelude::Digital`] records
//! ([`headers`]) and the Invariant CRC that protects them ([`icrc`]).
//!
//! # What is here, and what is not
//!
//! This is the stateless packet level — the first phase of
//! `roce-v2-architecture.md`. There is **no queue pair, no state and no
//! memory** here yet: given a header record you get its wire bytes, and
//! given a frame's bytes you get its ICRC. Message segmentation over
//! the path MTU, the PSN counter, the queue-pair context and the link
//! adapters are the next phase and are deliberately absent rather than
//! half-present.
//!
//! The direction built first is **send** — see that document's §5.2.
//! Parsing is partially present because the header records and their
//! packing are shared between the two directions, but the receive path
//! proper is not.
//!
//! # Why this belongs in a type system
//!
//! The IBTA opcode space is a transport service in the top three bits
//! and an operation in the low five, and the legal combinations are not
//! the cross product — Unreliable Connection supports SEND and RDMA
//! WRITE and nothing else. Every other implementation enforces that
//! with a comment, or does not enforce it. Here it is
//! [`headers::WriteOpcode`] and [`headers::Transport`], and an
//! unrepresentable combination cannot be built.
//!
//! # Validation
//!
//! Correctness here is not a matter of opinion: `tests/vectors.rs`
//! checks every header's bytes and every frame's ICRC against reference
//! packets generated by [Scapy](https://scapy.net)'s
//! `scapy.contrib.roce`, an independent implementation used in practice
//! to dissect real RoCE traffic. The vectors are committed; the
//! generator is `tools/gen_vectors.py` and is run deliberately.

