#![warn(missing_docs)]
//! RoCEv2 — RDMA over Converged Ethernet v2, in RHDL.
//!
//! A RoCEv2 packet is an ordinary UDP datagram to port 4791 whose
//! payload is an InfiniBand transport packet:
//!
//! ```text
//! +----------+-----------+--------+---------+-----------+---------+------+-----+
//! | Eth MAC  | IPv4 / v6 |  UDP   | IB BTH  | ext. hdrs | payload | ICRC | FCS |
//! |  14 B    | 20 / 40 B |  8 B   |  12 B   | 0/4/16 B  |  0..PMTU|  4 B | 4 B |
//! +----------+-----------+--------+---------+-----------+---------+------+-----+
//!                        dport=4791
//! ```
//!
//! Everything left of the BTH is ordinary networking. Everything from
//! the BTH rightward is InfiniBand, and that is what this crate covers:
//! the transport headers as typed [`rhdl::prelude::Digital`] records
//! ([`headers`]) and the Invariant CRC that protects them ([`icrc`]).
//!
//! # What is here, and what is not
//!
//! Phases 1 through 4 of `roce-v2-architecture.md` are present. The
//! packet
//! level is complete: given a header record you get its wire bytes, and
//! given a frame's bytes you get its ICRC. The send queue's decision
//! logic is complete too — [`qp::segmenter`] turns a message into the
//! right sequence of packets with the right opcodes, sequence numbers
//! and pad counts.
//!
//! [`frame`] wraps a packet into an Ethernet/IPv4/UDP frame, so the whole
//! header block of a real RoCEv2 frame is generated here and validated
//! byte-for-byte.
//!
//! The direction built first is **send** — see that document's §5.2 —
//! and it is complete from a work request to a finished frame's bytes:
//! [`tx`] walks a packet plan out byte by byte and [`endpoint`] drives
//! it from a queue of work requests.
//!
//! The receive direction is complete for UC WRITE. [`rx::parse`] turns
//! a frame's bytes back into typed headers, a verdict and a payload
//! stream; [`rx::verify`] recomputes the Invariant CRC and checks it;
//! [`qp::mr`] validates the R_Key and translates the address it
//! authorises; and [`rx::endpoint`] writes the payload there, tracking
//! per-queue-pair reassembly so a multi-packet message lands
//! contiguously. [`cm`] lets a queue pair and a region be negotiated
//! over UDP rather than compiled in, and [`cm::node`] puts the manager
//! and the receiver on one wire.
//!
//! Composing [`tx`] with the receiver closes the loop inside this
//! crate: a 2500-byte message is segmented, sent, received, verified,
//! authorised and placed byte-for-byte at the translated local
//! addresses — see `tests/loopback.rs`.
//!
//! What is **not** here, and is deliberately absent rather than
//! half-present:
//!
//! - **The link adapter** that puts a finished frame where a MAC can
//!   send it, or takes received bytes from one. Both directions end at
//!   a byte stream.
//! - **Reliable transport** — acknowledgements, sequence-number
//!   windows, retransmission. So a lost packet costs the remainder of
//!   its message and the next FIRST resynchronises, which is what
//!   Unreliable Connection means.
//! - **Congestion control** — no ECN reaction, no CNP, no rate limiter.
//! - **An arbiter.** Messages drain in posting order whatever queue
//!   pair they name.
//! - **Validation against a real host.** Everything here is checked
//!   against Scapy-generated bytes and against itself; no commodity
//!   RNIC has ever spoken to it. That is `roce-v2-architecture.md`
//!   §10's Tiers 7 and 8, and it is hardware-gated.
//!
//! # Why this belongs in a type system
//!
//! The IBTA opcode space is a transport service in the top three bits
//! and an operation in the low five, and the legal combinations are not
//! the cross product — Unreliable Connection supports SEND and RDMA
//! WRITE and nothing else. Every other implementation enforces that
//! with a comment, or does not enforce it. Here it is
//! [`headers::WriteOpcode`] and [`headers::Transport`], and an
//! unrepresentable combination cannot be built.
//!
//! # Validation
//!
//! Correctness here is not a matter of opinion: `tests/vectors.rs`
//! checks every header's bytes and every frame's ICRC against reference
//! packets generated by [Scapy](https://scapy.net)'s
//! `scapy.contrib.roce`, an independent implementation used in practice
//! to dissect real RoCE traffic. The vectors are committed; the
//! generator is `tools/gen_vectors.py` and is run deliberately.
//!
//! `tests/rx_vectors.rs` runs the same corpus the other way: given the
//! bytes Scapy produced, the parser must recover the fields Scapy was
//! given. Pinning the format from both sides is what makes the
//! transmit-into-receive loopback in `tests/loopback.rs` evidence
//! rather than a tautology — a shared misreading of the wire format
//! would have to survive the Scapy comparison in both directions
//! before it could reach the loop.

