//! PS/2 keyboard encoder (FPGA emulates a PS/2 keyboard)
//!
//! Wraps [super::ps2_device_tx::Ps2DeviceTx] with the Scan Code
//! Set 2 byte-encoding logic so the host can drive the FPGA at
//! the higher level "send a make event for scancode X" / "send a
//! break event for scancode X (extended? yes/no)" without dealing
//! with the prefix bytes (E0 / F0) directly.
//!
//! The widget maintains a small 4-byte transmit queue so the host
//! can hand off the entire byte sequence (up to E0 F0 X for an
//! extended-key release = 3 bytes) and let the wire-layer
//! transmitter push them out at the protocol's 12.5 kHz rate
//! without further host attention until the queue drains.
//!
//! ## Make / break encoding
//!
//! - Single-byte make: `tx_byte` = scancode, push directly.
//! - Single-byte break: push `0xF0`, then scancode.
//! - Extended make: push `0xE0`, then scancode.
//! - Extended break: push `0xE0`, `0xF0`, then scancode.
//!
//! Pause/Break and PrintScreen aren't generated by this widget —
//! the host can manually push the multi-byte sequences via a
//! lower-level interface if needed (or use the underlying
//! `ps2_device_tx` directly).
//!
//! Composes [super::ps2_device_tx::Ps2DeviceTx].
//!
//! Here is the schematic symbol
#![doc = badascii_doc::badascii_formal!(r"
     +-------+Ps2KeyboardEncoder+--------+
     |                                   |
B<8> |                                   | bool
+--->| scancode             clk_oe       +-->
bool |                                   | bool
+--->| make                 data_oe      +-->
bool |                                   | bool
+--->| extended             tx_busy      +-->
bool |                                   | bool
+--->| send                 ready        +-->
bool |                                   |
+--->| clk_in                            |
     +-----------------------------------+
")]
//!
//!# Internals
//!
//! Three-state FSM (Idle, EnqueuingPrefix, Sending).  When `send`
//! pulses with non-zero `make` and/or `extended`, the widget
//! enqueues the prefix bytes (0, 1, or 2) followed by the
//! scancode itself, then sequences them through the wire-layer
//! TX one byte at a time, waiting for `tx_done` from each.
//!
//!# Parameters
//!
//! - `DIV_W` — bit width of the wire-layer half-period divisor
//!   (passed through to `Ps2DeviceTx`).
//!
//!# Example
//!
//!```
#![doc = include_str!("../../examples/ps2_keyboard_encoder.rs")]
//!```
//!
//! The trace below demonstrates the result.
#![doc = include_str!("../../doc/ps2_keyboard_encoder.md")]
//!
